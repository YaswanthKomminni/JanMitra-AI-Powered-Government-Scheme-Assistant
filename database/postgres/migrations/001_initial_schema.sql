-- ====================================================================
-- JanMitra (PostgreSQL) migration 001: full schema
-- --------------------------------------------------------------------
-- * Repeatable: every statement uses IF NOT EXISTS / OR REPLACE.
-- * Never drops a table, column or row, and never deletes data.
-- * Applied by `npm run db:migrate` (frontend/), inside one transaction.
--
-- Tables
--   users                   accounts (bcrypt password_hash only)
--   user_sessions           server-side sessions (SHA-256 of the cookie token)
--   conversations           one chat thread, owned by one user
--   chat_logs               chat messages; belong to a conversation AND a user
--   schemes                 government scheme knowledge base
--   document_verifications  OCR-verified documents, per user
--   peer_success_stories    nearby-farmer stories
-- ====================================================================

-- Keeps updated_at current on UPDATE (replaces MySQL's ON UPDATE CURRENT_TIMESTAMP).
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- --------------------------------------------------------------------
-- users
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL,
    phone               VARCHAR(15)  NOT NULL,
    email               VARCHAR(100),
    password_hash       VARCHAR(255),  -- bcrypt only; NULL = password must be set by an admin
    role                VARCHAR(20)  NOT NULL DEFAULT 'farmer',
    state               VARCHAR(60)  DEFAULT 'Telangana',
    district            VARCHAR(60)  DEFAULT 'Rangareddy',
    village             VARCHAR(100) DEFAULT 'Kothur Gramam',
    land_size_acres     NUMERIC(5,2) DEFAULT 3.50,
    soil_type           VARCHAR(50)  DEFAULT 'black_soil',
    irrigation_type     VARCHAR(50)  DEFAULT 'drip',
    primary_crops       VARCHAR(255) DEFAULT 'Cotton, Chilli, Red Gram',
    annual_income_slab  VARCHAR(50)  DEFAULT 'Below ₹2.5 Lakhs',
    preferred_language  VARCHAR(10)  DEFAULT 'en',
    verified_docs_count INTEGER      NOT NULL DEFAULT 1,
    avatar_url          VARCHAR(500) DEFAULT 'https://images.unsplash.com/photo-1544717305-2782549b5136?w=150&auto=format&fit=crop&q=80',
    last_login_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_phone UNIQUE (phone),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_email_not_blank CHECK (email IS NULL OR btrim(email) <> ''),
    CONSTRAINT chk_users_password_is_bcrypt
        CHECK (password_hash IS NULL OR password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
);
CREATE INDEX IF NOT EXISTS idx_users_state ON users (state);

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- --------------------------------------------------------------------
-- user_sessions  (only a SHA-256 hash of the cookie token is stored)
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_sessions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash   CHAR(64)    NOT NULL,
    user_agent   VARCHAR(255),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_session_token UNIQUE (token_hash),
    CONSTRAINT chk_session_token_hex CHECK (token_hash ~ '^[0-9a-f]{64}$')
);
CREATE INDEX IF NOT EXISTS idx_session_user   ON user_sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_session_expiry ON user_sessions (expires_at);

-- --------------------------------------------------------------------
-- conversations
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS conversations (
    id         UUID        PRIMARY KEY,
    user_id    INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title      VARCHAR(160) NOT NULL DEFAULT 'New conversation',
    language   VARCHAR(10) DEFAULT 'en',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Target of chat_logs' composite foreign key (see below).
    CONSTRAINT uq_conversations_id_user UNIQUE (id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_conv_user_updated ON conversations (user_id, updated_at DESC);

-- --------------------------------------------------------------------
-- chat_logs  (the messages table)
-- --------------------------------------------------------------------
-- The composite foreign key (conversation_id, user_id) makes it impossible, at
-- the database level, to store a message under a conversation owned by a
-- different user. Deleting a conversation or a user deletes their messages.
CREATE TABLE IF NOT EXISTS chat_logs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER     NOT NULL,
    conversation_id   UUID        NOT NULL,
    client_message_id VARCHAR(80),
    sender            VARCHAR(4)  NOT NULL,
    message_text      TEXT        NOT NULL,
    language          VARCHAR(10) DEFAULT 'en',
    metadata          JSONB,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_chat_sender CHECK (sender IN ('user', 'ai')),
    CONSTRAINT fk_chat_conversation_owner
        FOREIGN KEY (conversation_id, user_id)
        REFERENCES conversations (id, user_id) ON DELETE CASCADE,
    CONSTRAINT fk_chat_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    -- One row per (user, client message id): a retried request never duplicates.
    CONSTRAINT uq_chat_client_msg UNIQUE (user_id, client_message_id)
);
CREATE INDEX IF NOT EXISTS idx_chat_conversation ON chat_logs (conversation_id, id);

-- --------------------------------------------------------------------
-- schemes
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS schemes (
    id                   VARCHAR(50)  PRIMARY KEY,
    code                 VARCHAR(50)  NOT NULL,
    name                 VARCHAR(255) NOT NULL,
    category             VARCHAR(50)  NOT NULL,
    category_name        VARCHAR(100) NOT NULL,
    match_score          INTEGER      DEFAULT 90,
    subsidy_amount       VARCHAR(150) NOT NULL,
    description          TEXT         NOT NULL,
    benefits             TEXT         NOT NULL,
    eligibility_summary  TEXT         NOT NULL,
    documents_required   JSONB        NOT NULL,
    department           VARCHAR(255) NOT NULL,
    tag_color            VARCHAR(100) DEFAULT 'bg-emerald-100 text-emerald-800 border-emerald-300',
    application_mode     VARCHAR(20)  DEFAULT 'both',
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_schemes_category ON schemes (category);

-- --------------------------------------------------------------------
-- document_verifications
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS document_verifications (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    doc_type         VARCHAR(50)  NOT NULL,
    title            VARCHAR(255) NOT NULL,
    confidence_score NUMERIC(4,2) DEFAULT 0.95,
    extracted_data   JSONB        NOT NULL,
    preview_url      VARCHAR(500),
    status           VARCHAR(30)  DEFAULT 'verified',
    verified_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_docver_user ON document_verifications (user_id);

-- --------------------------------------------------------------------
-- peer_success_stories
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS peer_success_stories (
    id                  VARCHAR(50)  PRIMARY KEY,
    farmer_name         VARCHAR(100) NOT NULL,
    distance_km         NUMERIC(5,2) NOT NULL,
    village             VARCHAR(100) NOT NULL,
    land_type           VARCHAR(100) NOT NULL,
    crops_grown         VARCHAR(100) NOT NULL,
    scheme_id           VARCHAR(50)  NOT NULL,
    scheme_name         VARCHAR(255) NOT NULL,
    outcome_summary     TEXT         NOT NULL,
    yield_increase_pct  INTEGER      DEFAULT 0,
    subsidy_received    VARCHAR(100) NOT NULL,
    implementation_date VARCHAR(50)  NOT NULL,
    contact_allowed     BOOLEAN      DEFAULT TRUE,
    contact_phone       VARCHAR(20)  NOT NULL,
    avatar_url          VARCHAR(500) NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_peers_distance ON peer_success_stories (distance_km);
